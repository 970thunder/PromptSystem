import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = path.join(root, 'docs', 'api-contract.schema.json')
const outputPath = path.join(root, 'src', 'frontend', 'src', 'types', 'api-contract.generated.ts')
const checkOnly = process.argv.includes('--check')
const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'))

const typeName = (name) => `ApiContract${name}`
const refName = (ref) => typeName(ref.split('/').at(-1))

function renderType(definition) {
  if (definition.$ref) return refName(definition.$ref)
  if (Array.isArray(definition.type)) {
    return definition.type.filter((item) => item !== 'null').map((item) => renderType({ type: item })).concat(definition.type.includes('null') ? ['null'] : []).join(' | ')
  }
  if (definition.enum) return definition.enum.map((value) => JSON.stringify(value)).join(' | ')
  if (definition.type === 'array') return `${renderType(definition.items)}[]`
  if (definition.type === 'object') {
    if (definition.additionalProperties) return 'Record<string, unknown>'
    return 'Record<string, never>'
  }
  if (definition.type === 'integer' || definition.type === 'number') return 'number'
  if (definition.type === 'boolean') return 'boolean'
  if (definition.type === 'string') return 'string'
  return 'unknown'
}

const lines = [
  '// This file is generated by scripts/generate-api-contract.mjs. Do not edit manually.',
  '',
  'export interface ApiContractApiResponse<T> {',
  '  code: number',
  '  message: string',
  '  errorCode?: string',
  '  data: T',
  '}',
  '',
  'export interface ApiContractPageResponse<T> {',
  '  list: T[]',
  '  total: number',
  '  page: number',
  '  pageSize: number',
  '}',
  ''
]

for (const [name, definition] of Object.entries(schema.definitions)) {
  const required = new Set(definition.required ?? [])
  lines.push(`export interface ${typeName(name)} {`)
  for (const [property, propertyDefinition] of Object.entries(definition.properties ?? {})) {
    const optional = required.has(property) ? '' : '?'
    lines.push(`  ${property}${optional}: ${renderType(propertyDefinition)}`)
  }
  if (definition.additionalProperties) {
    lines.push('  [key: string]: unknown')
  }
  lines.push('}', '')
}

const expected = `${lines.join('\n')}\n`
if (checkOnly) {
  const actual = fs.readFileSync(outputPath, 'utf8')
  if (actual !== expected) {
    console.error(`Generated API contract is stale: ${path.relative(root, outputPath)}`)
    process.exit(1)
  }
} else {
  fs.writeFileSync(outputPath, expected)
}
